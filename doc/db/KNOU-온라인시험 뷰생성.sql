CREATE OR REPLACE VIEW VW_USER AS
SELECT 	U.USER_ID 	USER_ID
		, A.AUTHRT_ID 	AUTHRT_ID
		, A.AUTHRTNM 	AUTHRTNM
		, UA.ORG_ID		ORG_ID
		, O.ORGNM		ORGNM
FROM 	TB_LMS_USER U
JOIN	TB_LMS_USER_AUTHRT UA 	ON 	U.USER_ID = UA.USER_ID
JOIN	TB_LMS_ORG O 			ON 	UA.ORG_ID = O.ORG_ID
JOIN	TB_LMS_AUTHRT	A 		ON	UA.AUTHRT_ID = A.AUTHRT_ID;



CREATE OR REPLACE VIEW VW_USER_SMSTR_CHRT AS
SELECT 		SMSTR.USER_ID
		, A.AUTHRT_ID
		, UA.ORG_ID
		, O.ORGNM
		, SC.SMSTR_CHRT_ID	
		, SC.DGRS_YR
		, SC.DGRS_SMSTR_CHRT
		, SC.SMSTR_CHRTNM
		, SC.SMSTR_CHRT_OP_SDTTM
		, SC.SMSTR_CHRT_OP_EDTTM
		, SC.PROF_ACCSS_PBL_SDTTM	PROF_ACCSS_PBL_SDTTM
FROM
( 
	SELECT	 DISTINCT SC.ORG_ID
			, U.USER_ID
			, SC.SMSTR_CHRT_ID	
			, SC.DGRS_YR
			, SC.DGRS_SMSTR_CHRT
	FROM 	TB_LMS_USER U
	INNER 	JOIN (	SELECT USER_ID, SBJCT_ID
	        		FROM TB_LMS_ATNDLC
	        		UNION ALL
			        SELECT USER_ID, SBJCT_ID
			        FROM TB_LMS_SBJCT_ADM
				) X ON X.USER_ID = U.USER_ID
	INNER JOIN TB_LMS_SBJCT S 			ON X.SBJCT_ID = S.SBJCT_ID AND S.USEYN = 'Y' AND S.DELYN = 'N'
	INNER JOIN TB_LMS_SMSTR_CHRT SC		ON SC.SMSTR_CHRT_ID = S.SMSTR_CHRT_ID
) SMSTR 
INNER JOIN TB_LMS_ORG O  			ON SMSTR.ORG_ID = O.ORG_ID
INNER JOIN TB_LMS_USER_AUTHRT UA	ON SMSTR.USER_ID = UA.USER_ID AND SMSTR.ORG_ID = UA.ORG_ID
INNER JOIN TB_LMS_AUTHRT A			ON UA.AUTHRT_ID = A.AUTHRT_ID
INNER JOIN TB_LMS_SMSTR_CHRT SC		ON SMSTR.SMSTR_CHRT_ID = SC.SMSTR_CHRT_ID;


