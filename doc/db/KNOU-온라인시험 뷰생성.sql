CREATE OR REPLACE VIEW VW_SBJCT_ADM AS
SELECT	S.SBJCT_ID
		, S.CRCLMN_NO
		, SA.SBJCT_ADM_TYCD
		, C.CDNM
		, U.USER_ID
		, U.USERNM
FROM	TB_LMS_SBJCT	S
INNER	JOIN	TB_LMS_SBJCT_ADM	SA	ON	S.SBJCT_ID = SA.SBJCT_ID
INNER	JOIN	TB_LMS_USER			U 	ON	SA.USER_ID = U.USER_ID
JOIN	TB_LMS_CMMN_CD				C	ON  C.LANG_CD = 'ko' 
										AND C.UP_CD = 'SBJCT_ADM_TYCD' AND C.CD = SA.SBJCT_ADM_TYCD;							
											
CREATE OR REPLACE VIEW VW_SBJCT_ATNDLC AS
SELECT	 ATND.SBJCT_ID
		, S.CRCLMN_NO
		, U.USER_ID
		, U.USERNM
		, U.DSBLYN
		, EB.EXAM_BSC_ID
		-- 1. 시험 디테일 분수(분) 직접 조회
		, (SELECT MIN(ED.CNSDR_ADD_MNTS) 
		   FROM TB_LMS_EXAM_DTL ED 
		   WHERE ED.EXAM_DTL_ID = EB.EXAM_BSC_ID) AS CNSDR_ADD_MNTS
		-- 2. 시험 디테일 비율 계산 (서브쿼리 중복을 피하기 위해 안에서 연산 처리)
		, (SELECT CASE WHEN MIN(ED.EXAM_MNTS) IS NULL OR MIN(ED.EXAM_MNTS) = 0 THEN 100
					   ELSE (MIN(ED.CNSDR_ADD_MNTS) / MIN(ED.EXAM_MNTS)) END
		   FROM TB_LMS_EXAM_DTL ED 
		   WHERE ED.EXAM_DTL_ID = EB.EXAM_BSC_ID) AS CNSDR_ADD_MNTS_RATE
		-- 3. 결시원 제출 여부 조회 (존재 여부만 파악하므로EXISTS나 MIN/MAX 활용)
		, CASE WHEN EXISTS (
					SELECT 1 
					FROM TB_LMS_EXAM_ABSNCE EA 
					WHERE EA.EXAM_BSC_ID = EB.EXAM_BSC_ID 
					  AND EA.USER_ID = ATND.USER_ID 
					  AND EA.ABSNCE_APLY_STSCD = 'APRV'
			   ) THEN '결시원제출'
			   ELSE '결시원미제출' 
		  END AS EXAM_ABSNCE_SBMSN_TYNM
FROM	TB_LMS_ATNDLC	ATND
INNER JOIN TB_LMS_SBJCT S	ON ATND.SBJCT_ID = S.SBJCT_ID
INNER JOIN TB_LMS_USER	U	ON ATND.USER_ID = U.USER_ID
INNER JOIN TB_LMS_EXAM_BSC EB ON ATND.SBJCT_ID = EB.SBJCT_ID 
                             AND EB.DELYN = 'N' 
                             AND EB.EXAM_TYCD = 'EXAM';

